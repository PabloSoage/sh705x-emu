"""Generates crates/engine/src/curves.rs from an A/D curve sweep.

    python tools/gen_curves.py <fase5-curvas-ad.json> crates/engine/src/curves.rs

The sweep (kept in the docs repository) booted the emulated ECU with one analog input
at a time set to 33 codes from 0 to 1023 and asked for the OBD PID or GMLAN identifier
that input moves. Each answer is decoded here to the physical value the firmware
reports, so the table says what code makes the ECU see a given value.
"""

import json
import sys


def u(b):
    return int.from_bytes(bytes(b), 'big')


# Request -> (key, name, unit, decoder of the data bytes after the request echo).
DECODE = {
    '222006': ('intake2', 'intake air temperature 2', 'degC', lambda d: d[0] - 40),
    '22323E': ('scv-feedback', 'rail pressure regulator current feedback', 'mA', lambda d: u(d)),
    '0149': ('pedal1', 'accelerator pedal sensor 1', '%', lambda d: d[0] * 100 / 255),
    '014A': ('pedal2', 'accelerator pedal sensor 2', '%', lambda d: d[0] * 100 / 255),
    '2232F4': ('fuel-temp', 'fuel temperature 1', 'degC', lambda d: d[0] - 40),
    '012F': ('fuel-level', 'fuel level', '%', lambda d: d[0] * 100 / 255),
    '0105': ('coolant', 'engine coolant temperature', 'degC', lambda d: d[0] - 40),
    '223218': ('fuel-temp2', 'fuel temperature 2', 'degC', lambda d: d[0] - 40),
    '221564': ('ac-pressure', 'A/C high side pressure', 'kPa', lambda d: d[0] * 14),
    '221152': ('egr', 'EGR valve position', '%', lambda d: d[0] * 100 / 255),
    '223273': ('dpf', 'DPF differential pressure', 'kPa', lambda d: d[0]),
    '010B': ('boost', 'boost (manifold) pressure', 'kPa', lambda d: d[0]),
    '0142': ('battery', 'system voltage', 'V', lambda d: u(d) / 1000),
    '0124': ('o2-voltage', 'wideband oxygen sensor voltage', 'V', lambda d: u(d[2:4]) * 8 / 65536),
    '0134': ('o2-current', 'wideband oxygen sensor current', 'mA', lambda d: u(d[2:4]) / 256 - 128),
    '0133': ('baro', 'barometric pressure', 'kPa', lambda d: d[0]),
    '013C': ('egt1', 'exhaust gas temperature 1', 'degC', lambda d: u(d) / 10 - 40),
    '013E': ('egt2', 'exhaust gas temperature 2', 'degC', lambda d: u(d) / 10 - 40),
    '0123': ('rail', 'fuel rail pressure', 'MPa', lambda d: u(d) * 0.01),
    '010F': ('intake', 'intake air temperature', 'degC', lambda d: d[0] - 40),
    '22327E': ('flap', 'intake manifold flap position', 'deg', lambda d: d[0] * 0.3529),
    '22201F': ('clutch', 'clutch pedal position sensor', '%', lambda d: d[0] * 100 / 255),
    # The firmware takes them as valid between codes ~800 and ~845 only: 5 V through a
    # 0.8 divider is code 818, which reads 231.8 here.
    # AN29 and AN30: a fault on AN30 sets bit 7 of identifier 0x2024, "5V Reference 1
    # Circuit Status" in GM's catalogue, and one on AN29 bit 6, "Reference 2".
    '221479': ('ref2', '5 V reference 2 (ratiometric base of the boost sensor)', 'V',
               lambda d: d[0] * 5 / 231.8),
    '221478': ('ref1', '5 V reference 1', 'V', lambda d: d[0] * 5 / 231.8),
    '221127': ('oil-level', 'engine oil level switch (1 = low)', '', lambda d: (d[0] >> 4) & 1),
}


def main():
    sweep = json.load(open(sys.argv[1], encoding='utf-8'))
    out = [
        '//! A/D transfer curves of the Astra J (A17DTJ) firmware: for each analog input, the',
        '//! value the ECU reports for 33 codes from 0 to 1023 [MED], measured on the emulated',
        '//! ECU by asking for the OBD PID or GMLAN identifier the input moves.',
        '//!',
        '//! Generated by tools/gen_curves.py; do not edit.',
        '',
        'use crate::sensors::Input;',
        '',
        '/// The analog inputs the firmware reads, by channel.',
        'pub static INPUTS: &[Input] = &[',
    ]
    for ch, req in sorted(sweep['pid'].items(), key=lambda kv: int(kv[0])):
        key, name, unit, dec = DECODE[req]
        pts = []
        for code, ans in sorted(sweep['curvas'][ch].items(), key=lambda kv: int(kv[0])):
            b = [int(x, 16) for x in ans.split()]
            pts.append((int(code), dec(b[len(req) // 2:])))
        curve = ', '.join(f'({c}, {v:.4g}_f64)' if '.' in f'{v:.4g}' or 'e' in f'{v:.4g}'
                          else f'({c}, {v:.4g}.0)' for c, v in pts)
        out += [
            '    Input {',
            f'        channel: {ch},',
            f'        key: "{key}",',
            f'        name: "{name}",',
            f'        unit: "{unit}",',
            f'        curve: &[{curve}],',
            '    },',
        ]
    out.append('];')
    open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
